        fn render(head: &ResponseHead<'_>) -> String {
            head.render(ConnectionVersion::Http11, ConnectionAction::KeepAlive)
        }

        /// Header lines of a rendered head, without the status line.
        fn header_lines(wire: &str) -> Vec<&str> {
            let (block, rest) = wire.split_once("\r\n\r\n").expect("head is terminated");
            assert!(rest.is_empty(), "nothing follows the head: {rest:?}");
            block.split("\r\n").skip(1).collect()
        }

        fn has_header(lines: &[&str], name: &str) -> bool {
            lines.iter().any(|line| {
                line.split_once(": ")
                    .is_some_and(|(n, _)| n.eq_ignore_ascii_case(name))
            })
        }

        #[test]
        fn success_head_has_via_date_connection_but_no_server() {
            let wire = render(&ResponseHead {
                content_length: Some(12),
                content_type: Some("application/octet-stream"),
                accept_ranges: true,
                last_modified: Some("Wed, 20 Dec 2023 04:45:32 GMT"),
                etag: Some("\"abc\""),
                age: Some(7),
                ..ResponseHead::bare(StatusCode::OK, ResponseKind::Success)
            });
            assert!(wire.starts_with("HTTP/1.1 200 OK\r\n"), "{wire}");
            let lines = header_lines(&wire);
            assert!(
                lines.contains(&format!("Via: {APP_VIA}").as_str()),
                "{wire}"
            );
            assert!(has_header(&lines, "Date"), "{wire}");
            assert!(lines.contains(&"Connection: keep-alive"), "{wire}");
            assert!(!has_header(&lines, "Server"), "{wire}");
            assert!(lines.contains(&"Content-Length: 12"), "{wire}");
            assert!(
                lines.contains(&"Content-Type: application/octet-stream"),
                "{wire}"
            );
            assert!(lines.contains(&"Accept-Ranges: bytes"), "{wire}");
            assert!(
                lines.contains(&"Last-Modified: Wed, 20 Dec 2023 04:45:32 GMT"),
                "{wire}"
            );
            assert!(lines.contains(&"ETag: \"abc\""), "{wire}");
            assert!(lines.contains(&"Age: 7"), "{wire}");
            assert!(!has_header(&lines, "Content-Range"), "{wire}");
            assert!(!has_header(&lines, "Retry-After"), "{wire}");
            assert!(!has_header(&lines, "Allow"), "{wire}");
        }

